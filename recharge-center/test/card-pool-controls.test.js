const apiDir=fs.mkdtempSync(path.join(os.tmpdir(),'gptc-card-control-api-'));
process.env.DATA_FILE=path.join(apiDir,'orders.json');process.env.ZZSHU_DB_FILE=path.join(apiDir,'cards.sqlite');

import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

test('Plus manual mode uses the same submission/query contract; optional card uses are durable and idempotent',async t=>{
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'gptc-manual-plus-'));
 process.env.DATA_FILE=path.join(dir,'orders.json');process.env.ZZSHU_DB_FILE=path.join(dir,'usage.sqlite');
 process.env.ADMIN_TOKEN='manual-fixture';process.env.RECOVERY_ENCRYPTION_KEY='manual-fixture-key';process.env.PUBLIC_BASE_URL='http://localhost';
 const {rechargeService:r}=await import('../src/recharge-service.js');const {JsonStore}=await import('../src/store.js');
 const {zzshuService:z}=await import('../src/zzshu-service.js');const {server}=await import('../src/server.js');const store=new JsonStore();
 await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));t.after(()=>{server.close();server.closeAllConnections();});
 const base='http://127.0.0.1:'+server.address().port;
 assert.equal((await fetch(base+'/api/admin/plus-fulfillment',{method:'POST',body:'{}'})).status,401);
 const login=await fetch(base+'/api/admin/login',{method:'POST',headers:{Origin:'http://localhost','Content-Type':'application/json','X-Admin-Request':'1'},body:JSON.stringify({password:'manual-fixture'})});
 const cookie=login.headers.get('set-cookie').split(';')[0],csrf=(await login.json()).data.csrf;
 const post=async(url,body)=>{const response=await fetch(base+url,{method:'POST',headers:{Cookie:cookie,Origin:'http://localhost','X-CSRF-Token':csrf,'Content-Type':'application/json'},body:JSON.stringify(body)});return {status:response.status,body:await response.json()};};
 const codes=r.createHCards({count:7,source:'微信'}).data.cards;
 const secret=JSON.stringify({user:{email:'manual@example.test'},account:{id:'manual-account'}});
 const submit=card=>r.confirmRecharge({cardInfo:card.code,secretJsonText:secret,provider:'h'});
 assert.equal(r.getProviderSettings().plusFulfillmentMode,'auto');
 assert.equal((await post('/api/admin/plus-fulfillment',{mode:'invalid'})).status,400);
 assert.equal((await post('/api/admin/plus-fulfillment',{mode:'manual'})).status,200);
 const first=await submit(codes[0]);assert.equal(first.data.status,'manual_queued');
 assert.equal((await submit(codes[0])).data.orderId,first.data.orderId);
 assert.equal((await r.confirmRecharge({cardInfo:codes[0].code,secretJsonText:JSON.stringify({user:{email:'other@example.test'},account:{id:'other'}})})).status,409);
 assert.equal((await r.queryHCardStatus(codes[0].code,'h')).data.canRecharge,false);
 assert.equal((await r.queryTaskStatus({orderId:first.data.orderId})).data.status,'manual_queued');
 await post('/api/admin/plus-fulfillment',{mode:'auto'});
 assert.equal((await submit(codes[0])).data.orderId,first.data.orderId);
 const complete=id=>'/api/admin/plus/orders/'+id+'/mark-success';
 assert.equal((await post(complete(first.data.orderId),{})).status,200);
 assert.equal(store.getHCardByCode(codes[0].code).status,'used');
 assert.equal((await r.queryTaskStatus({orderId:first.data.orderId})).data.status,'success');
 assert.equal((await r.queryTaskStatus({cardInfo:codes[0].code})).data.status,'success');
 assert.equal((await r.verifyCard(codes[0].code,'h')).ok,false);
 assert.equal(store.getOrder(first.data.orderId).manualPaymentUse.uses,0);
 await post('/api/admin/plus-fulfillment',{mode:'manual'});
 await z.importCards({text:'4242424242424242,12/40,123',source:'天空',maxSuccess:4});
 const manual=z.store.listCards().find(c=>c.credentialSource==='manual');
 const second=await submit(codes[1]),uid='manual:'+manual.id;
 assert.equal((await post(complete(second.data.orderId),{cardUid:uid,uses:5})).status,409);
 assert.equal(store.getOrder(second.data.orderId).status,'manual_queued');
 assert.equal((await post(complete(second.data.orderId),{cardUid:uid,uses:2})).status,200);
 assert.equal(z.store.listCards().find(c=>c.id===manual.id).remainingUses,2);
 await post(complete(second.data.orderId),{cardUid:uid,uses:2});await post(complete(second.data.orderId),{cardUid:uid,uses:1});
 assert.equal(z.store.listCards().find(c=>c.id===manual.id).remainingUses,2);
 store.syncHifupayCards([{id:'fixture-h',lastFour:'1001',status:'active',balance:40}]);
 const third=await submit(codes[2]);assert.equal((await post(complete(third.data.orderId),{cardUid:'h:fixture-h',uses:2})).status,200);
 store.syncHifupayCards([{id:'fixture-h',lastFour:'1001',status:'active',balance:40}]);
 assert.equal(store.listHifupayCards().find(c=>c.id==='fixture-h').remainingUses,2);
 const fourth=await submit(codes[3]);const originalWrite=store.write;
 // A failed JSON write after the durable usage entry can be retried without double consumption.
 const {createManualPlusService}=await import('../src/manual-plus.js');const {workbenchPaymentCards}=await import('../src/admin-workbench.js');
 const service=createManualPlusService({store,usage:z.store,listCards:()=>workbenchPaymentCards(store.listHifupayCards(),z.store.listCards(),0)});
 store.write=()=>{throw Error('fixture write failure');};
 assert.throws(()=>service.action(fourth.data.orderId,'mark-success',{cardUid:uid,uses:1}),/fixture write failure/);
 store.write=originalWrite;
 assert.equal(service.action(fourth.data.orderId,'mark-success',{cardUid:uid,uses:1}).ok,true);
 assert.equal(z.store.listCards().find(c=>c.id===manual.id).remainingUses,1);
 const fifth=await submit(codes[4]);z.store.updateCard(manual.id,{enabled:false});
 assert.equal((await post(complete(fifth.data.orderId),{cardUid:uid,uses:1})).status,409);
 assert.equal((await post('/api/admin/plus/orders/'+fifth.data.orderId+'/needs-info',{note:'fixture'})).status,200);
 assert.equal((await r.queryTaskStatus({orderId:fifth.data.orderId})).data.status,'needs_info');
 assert.equal((await post(complete(fifth.data.orderId),{})).status,200);
 store.updateHCard(codes[5].id,{expiresAt:'2020-01-01'});assert.equal((await submit(codes[5])).status,409);
 const sixth=await submit(codes[6]);store.updateOrder(sixth.data.orderId,{fulfillmentMode:'auto',status:'processing'});
 assert.equal((await post(complete(sixth.data.orderId),{})).status,404);
 assert.equal((await submit(codes[6])).data.orderId,sixth.data.orderId);
 assert.equal(store.getOrder(sixth.data.orderId).fulfillmentMode,'auto');
 assert.equal(r.getAdminWorkbench().orders.items.find(o=>o.id===third.data.orderId).manualPaymentUse.uses,2);
 assert.equal(store.read().rechargeLogs.some(log=>log.step.includes('start.submitting')),false);
});

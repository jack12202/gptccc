  assert.match(evidence.operator,/^admin:/); assert.equal(evidence.reasonCode,'token_expired');
  assert.equal(evidence.before,'needs_review'); assert.equal(evidence.after,'failed');
  const html=await fetch(base+'/admin/recoveries',{headers:{Cookie:cookie}}).then(r=>r.text());
  assert.match(html,/recoveryDialog/); assert.match(html,/解锁卡密/); assert.equal(html.includes('window.prompt'),false);
  for(const script of html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)) new vm.Script(script[1]);
  const activate=fs.readFileSync(path.resolve('activate/index.html'),'utf8');
